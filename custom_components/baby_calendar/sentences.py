"""Sentence files for Home Assistant's built-in conversation agent.

The built-in agent reads custom sentences from custom_sentences/<language>/
in the configuration folder. This module writes baby_calendar.yaml there
for each supported language: the templates in sentences/, plus lists of the
babies and their active medications. Only files that start with HEADER are
ever changed or deleted.
"""

from __future__ import annotations

import logging
from pathlib import Path
from typing import Any, Final

import yaml
from homeassistant.const import EVENT_HOMEASSISTANT_STOP
from homeassistant.core import Event, HomeAssistant, callback
from homeassistant.helpers.debounce import Debouncer
from homeassistant.util.hass_dict import HassKey

from .const import DOMAIN, MED_NAME
from .trackers.medication import medications
from .voice import loaded_babies, plain

_LOGGER = logging.getLogger(__name__)

LANGUAGES: Final = ("en", "pt")
FILE_NAME: Final = "baby_calendar.yaml"
HEADER: Final = "# Generated by Baby Calendar. Changes here are overwritten."
TEMPLATES: Final = Path(__file__).parent / "sentences"
MEDICATION_INTENT: Final = "BabyCalendarLogMedication"

DATA_DEBOUNCER: HassKey[Debouncer] = HassKey(f"{DOMAIN}_sentences")
DATA_WARNED: HassKey[set[Path]] = HassKey(f"{DOMAIN}_sentences_warned")


def sentence_path(hass: HomeAssistant, language: str) -> Path:
    """Return where a language's sentence file goes."""
    return Path(hass.config.path("custom_sentences", language, FILE_NAME))


def _values(names: list[tuple[str, str]]) -> list[dict[str, str]]:
    """Return list values for names, with an accentless variant where needed."""
    values: list[dict[str, str]] = []
    for name, out in names:
        values.append({"in": name, "out": out})
        if (bare := plain(name)) != name.casefold():
            values.append({"in": bare, "out": out})
    return values


def load_templates() -> dict[str, str]:
    """Read the sentence templates of each language."""
    return {
        language: (TEMPLATES / f"{language}.yaml").read_text(encoding="utf-8")
        for language in LANGUAGES
    }


def build(hass: HomeAssistant, templates: dict[str, str]) -> dict[str, str] | None:
    """Return each language's file content, or None without babies."""
    babies = loaded_babies(hass)
    if not babies:
        return None
    baby_names = [(entry.runtime_data.name, entry.entry_id) for entry in babies]
    med_names = [
        (med[MED_NAME], f"{entry.entry_id}:{med[MED_NAME]}")
        for entry in babies
        for med in medications(entry.options, active=True)
    ]
    contents: dict[str, str] = {}
    for language in LANGUAGES:
        template: dict[str, Any] = yaml.safe_load(templates[language])
        template["lists"]["baby"] = {"values": _values(baby_names)}
        if med_names:
            template["lists"]["medication"] = {"values": _values(med_names)}
        else:
            del template["intents"][MEDICATION_INTENT]
        body = yaml.safe_dump(template, allow_unicode=True, sort_keys=False)
        contents[language] = f"{HEADER}\n{body}"
    return contents


def is_ours(path: Path) -> bool:
    """Return whether a file is missing or was written by this module."""
    if not path.exists():
        return True
    with path.open(encoding="utf-8") as file:
        return file.readline().rstrip("\n") == HEADER


def _write(paths: dict[Path, str]) -> tuple[bool, list[Path]]:
    """Write changed files of ours; return whether any changed, and skipped ones."""
    changed, skipped = False, []
    for path, content in paths.items():
        if not is_ours(path):
            skipped.append(path)
            continue
        if path.exists() and path.read_text(encoding="utf-8") == content:
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        changed = True
    return changed, skipped


def _delete(paths: list[Path]) -> bool:
    deleted = False
    for path in paths:
        if path.exists() and is_ours(path):
            path.unlink()
            deleted = True
    return deleted


async def _reload_agent(hass: HomeAssistant) -> None:
    """Make the built-in agent read our languages' sentences again."""
    if not hass.services.has_service("conversation", "reload"):
        return
    for language in LANGUAGES:
        # With a language, the reload leaves configuration.yaml alone.
        await hass.services.async_call(
            "conversation", "reload", {"language": language}, blocking=True
        )


async def async_write(hass: HomeAssistant) -> None:
    """Write the sentence files for the loaded babies, and reload the agent."""
    if hass.is_stopping:
        return
    templates = await hass.async_add_executor_job(load_templates)
    contents = build(hass, templates)
    if contents is None:
        return
    paths = {sentence_path(hass, lang): text for lang, text in contents.items()}
    changed, skipped = await hass.async_add_executor_job(_write, paths)
    warned = hass.data.setdefault(DATA_WARNED, set())
    for path in skipped:
        if path not in warned:
            warned.add(path)
            _LOGGER.warning(
                "Not writing %s: it was not written by Baby Calendar. Rename or "
                "delete it to let Baby Calendar manage its voice sentences",
                path,
            )
    if changed:
        await _reload_agent(hass)


async def async_delete(hass: HomeAssistant) -> None:
    """Delete the sentence files of ours, and reload the agent."""
    paths = [sentence_path(hass, language) for language in LANGUAGES]
    if await hass.async_add_executor_job(_delete, paths):
        await _reload_agent(hass)


@callback
def async_setup_sentences(hass: HomeAssistant) -> None:
    """Prepare the debounced writer used when babies change."""

    async def write() -> None:
        await async_write(hass)

    debouncer = Debouncer(hass, _LOGGER, cooldown=1, immediate=False, function=write)
    hass.data[DATA_DEBOUNCER] = debouncer

    @callback
    def shutdown(_: Event) -> None:
        debouncer.async_shutdown()

    hass.bus.async_listen_once(EVENT_HOMEASSISTANT_STOP, shutdown)


@callback
def async_sentences_changed(hass: HomeAssistant) -> None:
    """Rewrite the sentence files soon, once for several changes."""
    if (debouncer := hass.data.get(DATA_DEBOUNCER)) is not None:
        debouncer.async_schedule_call()
